/**
 * Regenerates data/<catalog>/index.ts from the files in that folder, so adding
 * an entry is "drop a file, run npm run gen:index".
 */
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CATALOGS = [
  { dir: "data/ideologies", type: "IdeologyInput", exportName: "IDEOLOGIES" },
] as const;

for (const { dir, type, exportName } of CATALOGS) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && f !== "index.ts" && !f.endsWith(".test.ts"))
    .sort();
  const imports = files.map((f, i) => `import e${i} from "./${f.replace(/\.ts$/, "")}";`);
  const body = `// Generated by scripts/gen-catalog-index.ts. Do not edit by hand.
import type { ${type} } from "@/lib/schema/entries";
${imports.join("\n")}

export const ${exportName}: readonly ${type}[] = [${files.map((_, i) => `e${i}`).join(", ")}];
`;
  writeFileSync(join(dir, "index.ts"), body);
  console.log(`${dir}: ${files.length} entries`);
}
