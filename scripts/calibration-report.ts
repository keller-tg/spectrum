/** Prints the calibration tables and writes docs/calibration-report.md (PLAN §6.6, D-071). */
import { writeFileSync } from "node:fs";
import { loadIdeologies, toMatchable } from "@/lib/catalog/ideologies";
import { fitTau } from "@/lib/engine/calibrate";
import { runCalibration, GATE_SIGMA } from "@/lib/engine/calibration";
import {
  centristTopMatches,
  OFFSET_SDS,
  ROBUST_SIGMAS,
  runRobustness,
  STYLE_LIST,
  type RobustnessRow,
} from "@/lib/engine/robustness";
import { ENGINE_VERSION } from "@/lib/engine/version";
import { banks, shortHash } from "./derived-lib";
import { QUESTION_BANK } from "@/data/questions/bank";

const repeats = Number(process.env.CALIBRATION_REPEATS ?? 30);
const robustRepeats = Number(process.env.ROBUSTNESS_REPEATS ?? 10);
const MIXED = { sigma: 0.8, offsetSd: 0.5 };
const entries = loadIdeologies().map(toMatchable);
const tau = fitTau(entries);
const b = banks();
const report = runCalibration({ entries, banks: b, tau: tau.tau, repeats });
const robust = runRobustness({
  entries,
  banks: b,
  tau: tau.tau,
  repeats: robustRepeats,
  mixed: MIXED,
});
const centristMatches = centristTopMatches(b.standard, entries, tau.tau);

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const pts = (x: number) => x.toFixed(1);
const find = (mode: string, style: string, sigma: number, offsetSd: number) =>
  robust.find(
    (r) => r.mode === mode && r.style === style && r.sigma === sigma && r.offsetSd === offsetSd,
  ) as RobustnessRow;
const recoveryRow = (r: RobustnessRow, label: string) =>
  `| ${r.mode} | ${label} | ${pct(r.strict1)} | ${pct(r.strict3)} | ${pct(r.hit3)} | ${pct(r.quickHit)} | ${pts(r.mae)} | ${r.slope.toFixed(2)} | ${pct(r.lowQuality)} | ${r.inversions} |`;
const RECOVERY_HEAD = [
  "| Mode | Condition | strict@1 | strict@3 | spec hit@3 | quick hit | mean abs. error (pts) | slope | low quality | inversions |",
  "|---|---|---|---|---|---|---|---|---|---|",
];
const MODES = ["quick", "standard", "deep"] as const;

const lines = [
  "# Calibration report",
  "",
  `Generated by \`npm run calibration\` · engine ${ENGINE_VERSION} · question bank ${shortHash(QUESTION_BANK)} · ${report.entries} ideologies · τ = ${tau.tau.toFixed(1)}.`,
  "Simulated respondents are drawn from catalog coordinates, answer the real items, and are scored and matched by the real engine. Deep uses the bank structure until its items exist (Phase 9). Nothing here tunes the catalog or the items.",
  "",
  "## 1. Gates (spec, idealised respondents, σ = " + GATE_SIGMA + ")",
  "",
  `Answer = 2·key·coord/100 + N(0, σ²), rounded to the 5-point scale; every item equally easy to agree with. ${repeats} respondents per entry and noise level.`,
  "",
  "| Mode | Gate | Value | Threshold | Result |",
  "|---|---|---|---|---|",
  ...report.gates.map(
    (g) =>
      `| ${g.mode} | ${g.label} | ${pct(g.value)} | ${pct(g.threshold)} | ${g.pass ? "pass" : "**FAIL**"} |`,
  ),
  `| all | (c) archetype never ranked below a clearly opposite entry (σ ≤ ${GATE_SIGMA}) | | 0 inversions | ${report.inversionPass ? "pass" : "**FAIL**"} |`,
  "",
  "| Mode | σ | strict@1 | strict@3 | strict@5 | parent/child@3 | family@1 | spec hit@3 | quick hit | inversions |",
  "|---|---|---|---|---|---|---|---|---|---|",
  ...report.rows.map(
    (r) =>
      `| ${r.mode} | ${r.sigma} | ${pct(r.strict1)} | ${pct(r.strict3)} | ${pct(r.strict5)} | ${pct(r.lineage3)} | ${pct(r.family1)} | ${pct(r.hit3)} | ${pct(r.quickHit)} | ${r.inversions} |`,
  ),
  "",
  "Straight-lining (test b): every constant answer pattern scores exactly 0 on every axis and is flagged: " +
    (report.straightLine.every((s) => s.maxAbsScore === 0 && s.flagged) ? "**yes**" : "**NO**") +
    ` (${report.straightLine.length} patterns).`,
  "",
  "## 2. Robustness: response styles, noise and item difficulty",
  "",
  "Same archetypes, now answering like real people do. Latent answer = 2·key·coord/100 + offset_item + shift_style + N(0, σ²), then mapped to the scale by the style's thresholds.",
  "",
  ...STYLE_LIST.map(
    (s) =>
      `- **${s.id}**: ${s.label}; thresholds ${s.cuts.map((c) => (Number.isFinite(c) ? c : c > 0 ? "∞" : "−∞")).join(" / ")}${s.shift ? `, shift +${s.shift}` : ""}.`,
  ),
  `- **mixed**: each respondent gets one of the four styles at random, σ = ${MIXED.sigma}, item offsets SD ${MIXED.offsetSd}.`,
  `- **Item difficulty offsets**: each item gets a fixed offset ~ N(0, SD²) in answer steps (+ = easier to agree with), SD ∈ {${OFFSET_SDS.join(", ")}}; 10 independent draws per SD. Real offsets will come from the pilot.`,
  `- σ ∈ {${ROBUST_SIGMAS.join(", ")}}; ${robustRepeats} respondents per entry and condition.`,
  "",
  "**Columns.** strict@k: the respondent's own ideology ranked in the top k. spec hit@3: own ideology, parent/child or same family in the top 3 (the Standard/Deep gate metric). quick hit: own ideology in the top 5 or top match in the same family (the Quick gate metric). Mean abs. error: average |score − true coordinate| per axis. Slope: least-squares slope of score on true coordinate (below 1 = scores shrink toward the centre). Low quality: share flagged by the quality checks.",
  "",
  "### 2a. Headline: each style at σ = 0.8 with item offsets SD 0.3, plus the mixed population",
  "",
  ...RECOVERY_HEAD,
  ...MODES.flatMap((m) => [
    recoveryRow(find(m, "baseline", 0.5, 0), "gate setting (baseline, σ 0.5, no offsets)"),
    ...STYLE_LIST.map((s) => recoveryRow(find(m, s.id, 0.8, 0.3), `${s.id}, σ 0.8, offsets 0.3`)),
    recoveryRow(find(m, "mixed", MIXED.sigma, MIXED.offsetSd), "mixed, σ 0.8, offsets 0.5"),
  ]),
  "",
  "### 2b. Does a true centrist land at 0?",
  "",
  "Exact expected axis scores for a respondent whose every coordinate is 0 (computed from the answer distributions, not sampled). Max bias: the worst axis, median over the 10 offset draws (p90 in brackets). Mean bias: average |expected score| over axes. SD: spread of one centrist's axis score from answer noise alone, for comparison.",
  "",
  "| Mode | Style | σ | item offsets SD | max bias (p90) | mean bias | SD of one result |",
  "|---|---|---|---|---|---|---|",
  ...MODES.flatMap((m) =>
    [...STYLE_LIST.map((s) => s.id)].flatMap((st) =>
      OFFSET_SDS.map((o) => {
        const r = find(m, st, 0.8, o);
        return `| ${m} | ${st} | 0.8 | ${o} | ${pts(r.centrist.maxBias)} (${pts(r.centrist.maxBiasP90)}) | ${pts(r.centrist.meanBias)} | ${pts(r.centrist.sd)} |`;
      }),
    ),
  ),
  "",
  `Raw ranking (before the D-051 headline rule, which keeps a low-confidence entry out of the headline when a medium/high one is within 3 points): a simulated centrist (Standard, baseline style, σ 0.8, no offsets) is ranked closest to ${centristMatches
    .slice(0, 5)
    .map((c) => `${c.id} ${pct(c.share)}`)
    .join(", ")}.`,
  "",
  "<details><summary>2c. Full grid (every style × σ × offset SD × mode)</summary>",
  "",
  ...RECOVERY_HEAD,
  ...robust.map((r) => recoveryRow(r, `${r.style}, σ ${r.sigma}, offsets ${r.offsetSd}`)),
  "",
  "</details>",
  "",
  "## 3. Similarity curve (placeholder, re-tune on real data)",
  "",
  `Median best match ${tau.medianTop1Similarity.toFixed(1)}% · median 5th match ${tau.medianTop5Similarity.toFixed(1)}% · users with 3+ matches ≥ 90 %: ${pct(tau.shareThreeAbove90)} (population ${tau.population}).`,
  "",
];
writeFileSync("docs/calibration-report.md", lines.join("\n"));
console.log(lines.join("\n"));
process.exit(report.gates.every((g) => g.pass) && report.inversionPass ? 0 : 1);
